/**
 * Crea una copia limpia y fresca del inventario inicial de máquinas del catálogo
 */
export function createFreshInventory() {
  const items = JSON.parse(JSON.stringify(INITIAL_MACHINES_CATALOG));
  for (const m of items) {
    if (!m.clearanceOffsets) {
      m.clearanceOffsets = [0.00, 0.00, 0.00, 0.00];
    }
    if (m.quantity === undefined) {
      m.quantity = 1;
    }
  }
  return items;
}

